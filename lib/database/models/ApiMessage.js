const { DataTypes, ValidationError, ValidationErrorItem } = require("sequelize");

// Literals repeated on purpose (see ApiKey.js): a model cannot import an engine constant. A test pins that
// STATUSES equals lib/messaging/errors.js.
const SOURCES = ["api", "panel"];
const STATUSES = ["queued", "sending", "sent", "delivered", "read", "failed", "expired", "cancelled", "unknown"];
const PN_JID = /^[1-9]\d{7,14}@s\.whatsapp\.net$/;
const GROUP_JID = /^\d{5,25}(-\d+)?@g\.us$/;
const MAX_PAYLOAD_BYTES = 128 * 1024;

/**
 * ApiMessage Model
 * One send requested by an API key or by the panel test form (specs/004-messaging-api, data-model 2). Metadata
 * only: the clear text of a message exists in `payload` and in the staged file at `mediaPath`, and only while the
 * status is `queued` or `sending` (data-model 2.6); every transition that leaves those two statuses erases both
 * in the same UPDATE. Excluded from backups.
 *
 * Status machine (data-model 2.5): queued -> sending -> sent -> delivered -> read, with the exits failed, expired,
 * cancelled and unknown. Every transition is one conditional `UPDATE ... WHERE id = :id AND status = :from`.
 * `format` and `errorCode` are open sets (formats are modules, the code catalogue belongs to the engine): no isIn.
 * The invariants I1-I9 are asserted by test/helpers/apiInvariants.js; the model enforces only what a single row
 * can say on its own.
 *
 * JSON columns (`payload`, `choices`, `replyData`) are read through model instances, never `raw: true`: a string
 * on SQLite. Erase them with `null` (a SQL NULL), not an empty value.
 */
module.exports = (sequelize) => {
  const ApiMessage = sequelize.define(
    "ApiMessage",
    {
      id: {
        type: DataTypes.INTEGER,
        primaryKey: true,
        autoIncrement: true,
        comment: "Internal; ascending = FIFO order of acceptance; the panel's message id",
      },
      publicId: {
        type: DataTypes.STRING(32),
        allowNull: false,
        validate: { is: /^msg_[A-Za-z0-9_-]{22}$/ },
        comment: "msg_ + 22 base64url characters; the only id the public API shows",
      },
      apiKeyId: {
        type: DataTypes.INTEGER,
        allowNull: true,
        comment: "Logical link to api_keys.id; NULL for source panel",
      },
      source: {
        type: DataTypes.STRING(5),
        allowNull: false,
        defaultValue: "api",
        validate: { isIn: [SOURCES] },
        comment: "api | panel",
      },
      idempotencyKey: {
        type: DataTypes.STRING(80),
        allowNull: true,
        validate: { is: /^[A-Za-z0-9._:-]{1,80}$/ },
        comment: "The Idempotency-Key header; NULLed 24 h after acceptance",
      },
      requestHash: {
        type: DataTypes.STRING(64),
        allowNull: true,
        comment: "Keyed fingerprint of the request; NULL exactly when idempotencyKey is NULL",
      },
      recipient: {
        type: DataTypes.STRING(64),
        allowNull: false,
        validate: {
          jid(value) {
            if (typeof value !== "string" || !(PN_JID.test(value) || GROUP_JID.test(value))) {
              throw new Error("recipient must be <digits>@s.whatsapp.net or <id>@g.us");
            }
          },
        },
        comment: "Requested target, normalised; never a LID",
      },
      format: {
        type: DataTypes.STRING(24),
        allowNull: false,
        validate: { is: /^[a-z][a-z0-9_]{1,23}$/ },
        comment: "Format module name (open set)",
      },
      size: {
        type: DataTypes.INTEGER,
        allowNull: true,
        comment: "Bytes of the accepted input media, or UTF-8 length of the text; never content",
      },
      status: {
        type: DataTypes.STRING(10),
        allowNull: false,
        defaultValue: "queued",
        validate: { isIn: [STATUSES] },
        comment: "queued sending sent delivered read failed expired cancelled unknown",
      },
      errorCode: {
        type: DataTypes.STRING(40),
        allowNull: true,
        comment: "Stable snake_case reason owned by the engine catalogue (open set)",
      },
      waId: {
        type: DataTypes.STRING(64),
        allowNull: true,
        comment: "WhatsApp message id, generated by the engine and written at the claim",
      },
      requestId: {
        type: DataTypes.STRING(16),
        allowNull: true,
        comment: "X-Request-Id of the accepting request; NULL for panel rows",
      },
      acceptedAt: {
        type: DataTypes.DATE,
        allowNull: false,
        comment: "Engine clock at acceptance",
      },
      expiresAt: {
        type: DataTypes.DATE,
        allowNull: false,
        comment: "acceptedAt + API_QUEUE_EXPIRY_MIN as set at acceptance",
      },
      sendingAt: { type: DataTypes.DATE, allowNull: true, comment: "The claim" },
      sentAt: { type: DataTypes.DATE, allowNull: true, comment: "WhatsApp accepted the message" },
      deliveredAt: { type: DataTypes.DATE, allowNull: true, comment: "Delivery receipt time" },
      readAt: { type: DataTypes.DATE, allowNull: true, comment: "Read receipt time" },
      endedAt: {
        type: DataTypes.DATE,
        allowNull: true,
        comment: "Transition into failed, expired, cancelled or unknown",
      },
      repliesUntil: {
        type: DataTypes.DATE,
        allowNull: true,
        comment: "Interactive formats only: reply capture records while now <= repliesUntil",
      },
      payload: {
        type: DataTypes.JSON,
        allowNull: true,
        validate: {
          size(value) {
            if (Buffer.byteLength(JSON.stringify(value) || "", "utf8") > MAX_PAYLOAD_BYTES) {
              throw new Error("payload: at most 128 KiB");
            }
          },
        },
        comment: "Transient content, only while queued or sending; at most 128 KiB",
      },
      choices: {
        type: DataTypes.JSON,
        allowNull: true,
        comment: "[{ id, label }] of an interactive message, kept for the retention period",
      },
      replyData: {
        type: DataTypes.JSON,
        allowNull: true,
        comment: "Poll option digests; NULLed when repliesUntil passes",
      },
      pollSecret: {
        type: DataTypes.STRING(255),
        allowNull: true,
        comment: "enc:v1: ciphertext of the poll messageSecret; never serialised",
      },
      mediaPath: {
        type: DataTypes.STRING(255),
        allowNull: true,
        comment: "Repo-relative path of the staged source file; NULLed after deletion",
      },
    },
    {
      tableName: "api_messages",
      timestamps: true,
      indexes: [
        { unique: true, fields: ["publicId"] },
        { unique: true, fields: ["apiKeyId", "idempotencyKey"] },
        { unique: true, fields: ["waId"] },
        { fields: ["status", "acceptedAt"] },
        { fields: ["apiKeyId", "status"] },
        { fields: ["apiKeyId", "acceptedAt"] },
        { fields: ["acceptedAt"] },
      ],
      hooks: {
        // source = 'api' <=> apiKeyId IS NOT NULL, checked on create and save. A static Model.update() validates a
        // partial build where `source` falls back to its default and `apiKeyId` is absent: it lists the attributes
        // it does not set in `options.skip`, and a status UPDATE must never be refused by this rule.
        beforeValidate(instance, options) {
          const skipped = (options && options.skip) || [];
          if (skipped.includes("apiKeyId") || skipped.includes("source")) return;
          const hasKey = instance.apiKeyId !== null && instance.apiKeyId !== undefined;
          if ((instance.source === "api") !== hasKey) {
            const message = "apiKeyId is required for source api and must be empty for source panel";
            throw new ValidationError(null, [new ValidationErrorItem(message, "Validation error", "apiKeyId", instance.apiKeyId)]);
          }
        },
      },
    }
  );

  return ApiMessage;
};
